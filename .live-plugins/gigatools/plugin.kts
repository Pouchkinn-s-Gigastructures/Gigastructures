val textGeneratedBlock = "WARNING: The contents of this block are generated by script, any manual changes will be overwritten"


fun getElementName(element: ParadoxScriptDefinitionElement) : String? {
    val locale = ParadoxLocaleManager.getLocaleConfig("en") // english for standardisation
    val selector = selector(element.project, element).localisation().contextSensitive().preferLocale(locale)
    val loc = ParadoxLocalisationSearch.search(element.name, selector).find()
    if (loc == null) { return element.name }
    val rendered = ParadoxLocalisationTextRenderer.render(loc).replace("\u200B", "")
    return if(rendered.isNotEmpty()) rendered else loc.value ?: element.name
}

// rewrite the body of a specified scripted trigger with a list of megas which have the matching economic category or a child thereof
fun buildMegaCategoryList(project: Project, triggerName: String, categoryName: String) {
    val selector = selector(project, project.projectFile).definition()

    // find the trigger that we're going to rewrite
    val trigger = ParadoxDefinitionSearch.search(triggerName,"scripted_trigger", selector).find()
    if (trigger == null) {
        show("Failed to find scripted trigger: $triggerName")
        return
    }

    // find the economic category we're checking against
    val wantedCategory = ParadoxDefinitionSearch.search(categoryName,"economic_category", selector).find()
    if (wantedCategory == null) {
        show("Failed to find economic category: $categoryName")
        return
    }

    // start the block's text with a warning and description
    val builder = StringBuilder().append("{").appendLine("\t# $textGeneratedBlock")
    builder.appendLine("\t# Lists megas with an economic category equal to $categoryName, or one of its descendant categories").appendLine()
    builder.appendLine("\tor = {")

    // get a list of matching megas
    val megas: Set<ParadoxScriptDefinitionElement> = ParadoxDefinitionSearch.search("megastructure", selector).findAll()
    for (mega in megas) {
        val resources = mega.findProperty("resources", inline = true)
        if (resources == null) { builder.appendLine("# ${mega.name}: no resource block"); continue }

        val megaCategoryName = resources.findProperty("category", inline = true)?.value
        if (megaCategoryName == null) { builder.appendLine("# ${mega.name}: no category given"); continue }
        val category = ParadoxDefinitionSearch.search(megaCategoryName, "economic_category", selector).find()
        if (category != wantedCategory) { builder.appendLine("# ${mega.name}: wrong category -> ${category?.name ?: "not given"}"); continue }

        val locName = getElementName(mega)

        builder.append("\t\t\$TRIGGER\$ = ${mega.name}")
        if (locName != null) {
            builder.append(" # $locName")
        }
        builder.appendLine()
    }

    // create a new block with info and content
    builder.appendLine("\t}").appendLine("}")
    val newBlock = ParadoxScriptElementFactory.createBlock(project, builder.toString())

    // finally, swap the trigger's block for the new one
    trigger.block?.replace(newBlock)
}

